const PDFDocument = require('pdfkit');

/**
 * Streams a prescription PDF into the response.
 * `rx` must be populated with patientId and doctorId.
 */
module.exports = (rx, res) => {
  const doc = new PDFDocument({ margin: 50 });
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `attachment; filename="prescription-${rx._id}.pdf"`);
  doc.pipe(res);

  doc.fontSize(22).fillColor('#0f766e').text('Clinic Prescription', { align: 'center' });
  doc.moveDown(0.3);
  doc.fontSize(10).fillColor('#555').text(`Date: ${new Date(rx.createdAt).toLocaleDateString()}`, { align: 'center' });
  doc.moveDown();
  doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor('#0f766e').stroke();
  doc.moveDown();

  doc.fillColor('#000').fontSize(12);
  doc.text(`Patient: ${rx.patientId.name}`);
  doc.text(`Age / Gender: ${rx.patientId.age} / ${rx.patientId.gender}`);
  doc.text(`Doctor: Dr. ${rx.doctorId.name}${rx.doctorId.specialization ? ' (' + rx.doctorId.specialization + ')' : ''}`);
  if (rx.diagnosis) doc.text(`Diagnosis: ${rx.diagnosis}`);
  doc.moveDown();

  doc.fontSize(14).fillColor('#0f766e').text('Medicines');
  doc.moveDown(0.3);
  doc.fontSize(11).fillColor('#000');
  rx.medicines.forEach((m, i) => {
    doc.text(`${i + 1}. ${m.name} - ${m.dosage}`, { continued: false });
    const extra = [m.frequency, m.duration].filter(Boolean).join(' | ');
    if (extra) doc.fillColor('#555').text(`    ${extra}`).fillColor('#000');
    if (m.notes) doc.fillColor('#555').text(`    Note: ${m.notes}`).fillColor('#000');
  });

  if (rx.instructions) {
    doc.moveDown();
    doc.fontSize(14).fillColor('#0f766e').text('Instructions');
    doc.fontSize(11).fillColor('#000').text(rx.instructions);
  }

  doc.moveDown(2);
  doc.fontSize(9).fillColor('#888').text('Generated by Clinic Management System', { align: 'center' });
  doc.end();
};
